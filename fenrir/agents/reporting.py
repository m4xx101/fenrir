class ReportingAgent(BaseAgent):
    """Reporting agent that consumes all findings from brain.

    Generates:
    1. Executive summary (markdown)
    2. Technical report (markdown)
    3. Chain impact analysis (markdown)

    All reports are saved as markdown files in the target's brain directory.
    """

    name = "reporting"
    role = "reporting"
    system_prompt = """You are Fenrir Pro-Max's Reporting Agent.

Your role is to aggregate all security assessment findings and produce
comprehensive reports:
- Executive summary for management
- Technical report for engineers
- Chain impact analysis for security architects"""
    tier = LLMTier.TIER_1

    async def _run(self, task: str, context: str) -> AgentResult:
        target = self.target or task.strip().split()[-1]
        findings = []

        try:
            start_time = time.monotonic()

            # Gather all data from brain
            all_vulns = self.brain.query_vulns(target=target)
            all_recon = self.brain.query_recon(target=target)
            all_chains = self.brain.query_chains(target=target)

            # Combine all findings
            combined_findings = all_vulns + all_recon

            elapsed = time.monotonic() - start_time

            # Generate reports
            reports = {}

            # 1. Executive summary
            exec_report = make_executive_report(
                target=target,
                findings=combined_findings,
                chains=all_chains,
                scan_duration=f"{elapsed:.1f}s",
            )
            exec_path = self._save_report(target, "executive_summary", exec_report)
            reports["executive_summary"] = str(exec_path)

            # 2. Technical report
            tech_report = make_technical_report(
                target=target,
                findings=combined_findings,
                chains=all_chains,
                vulns=all_vulns,
                recon_data=all_recon,
            )
            tech_path = self._save_report(target, "technical_report", tech_report)
            reports["technical_report"] = str(tech_path)

            # 3. Chain impact analysis
            chain_report = make_chain_impact_report(
                target=target,
                chains=all_chains,
                all_findings=combined_findings,
            )
            chain_path = self._save_report(target, "chain_impact_analysis", chain_report)
            reports["chain_impact_analysis"] = str(chain_path)

            findings.append({
                "type": "report_generated",
                "target": target,
                "reports": reports,
                "stats": {
                    "total_vulns": len(all_vulns),
                    "total_recon": len(all_recon),
                    "total_chains": len(all_chains),
                },
            })

            logger.info(f"[{self.name}] Generated 3 reports for {target}")

            return AgentResult(
                agent_name=self.name,
                success=True,
                summary=f"Generated 3 reports: executive, technical, chain analysis",
                findings=findings,
            )

        except Exception as e:
            logger.error(f"[{self.name}] Report generation failed: {e}")
            return AgentResult(
                agent_name=self.name,
                success=False,
                error=str(e),
                findings=[],
            )

    def _save_report(self, target: str, report_type: str, content: str) -> Path:
        """Save a report as a markdown file in the target directory."""
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        safe_target = target.replace("://", "_").replace("/", "_").replace(".", "_")
        filename = f"{safe_target}_{report_type}_{timestamp}.md"

        target_dir = self.config.brain.base_dir / "targets" / safe_target
        target_dir.mkdir(parents=True, exist_ok=True)

        filepath = target_dir / filename
        filepath.write_text(content, encoding="utf-8")

        logger.info(f"[{self.name}] Saved report: {filepath}")
        return filepath
